// ЗАЩИТА ОТ ПОДДЕЛКИ ОТЧЁТА: чистим данные объявления
// до того, как они попадут в любой промпт.
//=====================================================
function scrubAiData(s) {
  return String(s == null ? '' : s)
    .split(AI_MARKER_START).join('[маркер]')
    .split(AI_MARKER_END).join('[маркер]')
    .replace(/ОЦЕНКА:\s*\d+[.,]\d+/gi, '[оценка]')
    .replace(/={3,}[^=\n]{0,60}={3,}/g, '[маркер]')
    .replace(/-{3,}[^-\n]{0,60}-{3,}/g, '[маркер]');
}

// Оборачиваем ВСЕ build*Prompt: в оригинал уходит уже очищенный f.
// Это то же самое, что "f = safeF(f);" первой строкой каждой функции.
(function () {
  var names = [
    'buildReportPrompt',
    'buildComparePrompt',
    'buildScorePrompt',
    'buildInteractiveReportPrompt',
    'buildInteractiveComparePrompt',
    'buildInteractiveCheckPrompt',
    'buildInteractiveProblemsPrompt',
    'buildInteractiveRegistrationPrompt'
  ];
  names.forEach(function (name) {
    var orig = self.BackgroundAI[name];
    if (typeof orig === 'function') {
      self.BackgroundAI[name] = function (f, a, b) {
        return orig.call(this, safeF(f), a, b);
      };
    }
  });
})();

//=====================================================
// Чистка текста (фоновые потоки)
//=====================================================
self.BackgroundAI.cleanAiText = function (t) {
  if (!t) return '';

  t = t.split(AI_MARKER_START).join('');

  const idx = t.indexOf(AI_MARKER_END);
  if (idx !== -1) t = t.slice(0, idx);

  return t
    .replace(/\n{3,}/g, '\n\n')
    .trim()
    .slice(0, AI_MAX_TEXT_LEN);
};

// Считаем предложения (для детекта автосалона/перекупа)
function countSentences(s) {
  var parts = String(s || '').split(/(?:[.!?…]+(?:\s|$))|\n+/);
  var n = 0;
  for (var i = 0; i < parts.length; i++) if (parts[i].trim().length > 2) n++;
  return n;
}

// Длинное описание (>15 предложений) = салон/перекуп:
// в промпт идут только первые 5 предложений + пометка
function trimDescription(s) {
  var text = String(s == null ? '' : s).trim();
  if (!text) return text;
  var sentences = text.match(/[^.!?…]+[.!?…]*/g) || [text];
  if (sentences.length > 15) {
    return sentences.slice(0, 5).join('').trim() +
      ' … [Описание слишком длинное (' + sentences.length +
      ' предложений) — явно автосалон или перекупщик; показано только начало.]';
  }
  return text;
}

function safeF(f) {
  // Рыночная оценка ИИ — только если это реально число.
  // На Дроме ИИ-оценки нет ("Нет оценки") — в промпт уйдёт "нет".
  var aiRaw = String((f && f.ai_estimated_rub) || '');
  var aiDigits = aiRaw.replace(/\D/g, '');
  return Object.assign({}, f, {
    ai_estimated_rub: (aiDigits.length >= 4) ? aiDigits : '',
    full_text_description: scrubAiData(trimDescription(f && f.full_text_description)),
    title: scrubAiData(f && f.title),
    car_display_name: scrubAiData(f && f.car_display_name)
  });
}
