self.BackgroundAI = self.BackgroundAI || {};

//=====================================================
// Уникальные маркеры на каждый запрос (2-3 отчёта подряд)
//=====================================================
self.BackgroundAI.makeRunMarkers = function () {
  var chars = 'ABCEHKMPTX0123456789';
  var id = '';
  for (var i = 0; i < 6; i++) {
    id += chars[Math.floor(Math.random() * chars.length)];
  }
  return {
    aiMarkerStart: '===НАЧАЛО ОТЧЁТА [' + id + ']===',
    aiMarkerEnd: '-----------------КОНЕЦ ОТЧЁТА [' + id + ']-----------------'
  };
};

//=====================================================
// Эталонное авто из настроек (выпадающий список попапа).
// Эталонное состояние = половина типового ресурса авто.
//=====================================================
function fmtKm(n) {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

self.BackgroundAI.getRefCar = function (settings) {
  const key = (settings && settings.compare) || DEFAULT_COMPARE_CAR;
  const cars = (typeof COMPARE_CARS !== 'undefined' && COMPARE_CARS) ? COMPARE_CARS : {};
  const base = cars[key] || cars[DEFAULT_COMPARE_CAR] || cars.yaris || {};

  const resource = Number(base.resource) > 0 ? Number(base.resource) : 300000;
  const half = Math.round(resource / 2 / 1000) * 1000;

  return {
    key: key,
    name: base.name || 'Toyota Yaris (2 пок., XP90)',
    years: base.years || '2005–2011',
    resource: resource,
    half: half
  };
};

// Одна строка-эталон для всех промптов
self.BackgroundAI.refLine = function (ref) {
  return 'Эталоном надёжности (ровно 10,0 из 10) для этой шкалы является ' + ref.name + ' (' + ref.years + ') ' +
    'в состоянии половины типового ресурса: пробег около ' + fmtKm(ref.half) + ' км ' +
    '(полный ресурс около ' + fmtKm(ref.resource) + ' км), своевременное обслуживание, не битый.';
};

//=====================================================
// ФОН: отчёт для ZIP (эталон = выбранное авто)
//=====================================================
self.BackgroundAI.buildReportPrompt = function (f, opts) {
  const S = (opts && opts.aiMarkerStart) || AI_MARKER_START;
  const E = (opts && opts.aiMarkerEnd) || AI_MARKER_END;
  const ref = (opts && opts.refCar) || self.BackgroundAI.getRefCar(opts);

  let scoreBlock;

  if (opts && opts.scoreFixed != null && isFinite(opts.scoreFixed)) {
    const sc = Number(opts.scoreFixed).toFixed(1).replace('.', ',');
    scoreBlock =
      '5. Оценка целесообразности покупки.\n' +
      'Система УЖЕ рассчитала итоговую оценку этого экземпляра по единой методике (эталон — ' + ref.name + '): ' + sc + ' из 10.\n' +
      'СТРОГО используй именно эту оценку, не придумывай другую, и заверши пункт строкой: ОЦЕНКА: ' + sc + '\n\n';
  } else {
    scoreBlock =
      '5. Оценка целесообразности покупки по шкале от 1.0 до 10.0 строго с десятыми долями (например: 6,5).\n' +
      self.BackgroundAI.refLine(ref) + '\n' +
      'Заверши пункт строкой: ОЦЕНКА: X,X\n\n';
  }

  return 'Роль: Действуй как профессиональный автоэксперт. Составь критический техотчёт по авто ' + f.car_display_name + '.\n' +
    'Распиши строго по пунктам:\n' +
    '1. Проблемность и скрытые риски.\n' +
    '2. Ремонтопригодность и доступность запчастей.\n' +
    '3. Болячки этого мотора + КПП.\n' +
    '4. Главные преимущества.\n' +
    scoreBlock +
    'Важно! В начале ответа поставь символьную строку: ' + S + '\n' +
    'Важно! В конце ответа по авто поставь символьную строку: ' + E;
};

